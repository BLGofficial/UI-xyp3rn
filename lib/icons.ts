/**
 * Looks up an icon by its data name.
 * @param name Lucide icon name from a job or sector
 * @returns the icon, or a dashed circle when the name is unknown
 */
export function resolveIcon(name: string): LucideIcon {
  return ICONS[name] ?? CircleDashed;
}
