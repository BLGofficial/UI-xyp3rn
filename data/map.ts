const STUB_LADDER: Record<Autonomy, string> = {
  'human-led': ui.stub.text,
  'human-assisted': ui.stub.text,
  'fully-autonomous': ui.stub.text,
};

function stubJob(
  id: string,
  sector: DepartmentId,
  cluster: string,
  fileName: string,
  title: string,
  icon: string,
  note?: string,
): Job {
  return {
    id,
    file: `${sector}/${cluster}/${fileName}`,
    title,
    cluster,
    summary: ui.stub.text,
    icon,
    // The type requires a level; the UI shows the STUB eyebrow instead of this value.
    autonomy: 'human-led',
    status: 'not-started',
    breaksInto: [],
    buildsOn: [],
    replaces: ui.stub.text,
    ladder: STUB_LADDER,
    human: ui.stub.text,
    buildNotes: note ? ui.stub.source.replace('{note}', note) : ui.stub.text,
    skill: { name: id, blurb: ui.stub.text, markdown: `${ui.stub.text}\n`, installCmd: ui.stub.text },
    stub: true,
  };
}

/** A note the source spec names (so the title and path are real) but never writes. */
function namedStub(
  id: string,
  sector: DepartmentId,
  cluster: string,
  fileName: string,
  icon: string,
  note?: string,
): Job {
  return stubJob(id, sector, cluster, fileName, fileName.replace(/\.md$/, ''), icon, note);
}

/** A note the source spec only counts ("plus 1 // STUB"); `kind` is the spec's own wording. */
function unnamedStub(
  sector: DepartmentId,
  cluster: string,
  kind: string,
  n: number,
  of: number,
  note?: string,
): Job {
  const suffix = of > 1 ? ` ${n}` : '';
  const slug = cluster.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return stubJob(
    `stub-${sector.slice(0, 2)}-${slug}-${n}`,
    sector,
    cluster,
    `STUB ${kind}${suffix}.md`,
    `${ui.stub.titlePrefix} · ${kind}${suffix}`,
    'CircleDashed',
    note,
  );
}

